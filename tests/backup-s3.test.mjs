import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { once } from 'node:events';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'backup-s3-'));
process.env.QQ_AGENT_DATA_DIR = temp;
const { createS3Target, signS3Request, buildS3Url } = await import('../src/backup/targets/s3.js');
after(() => fs.rmSync(temp, { recursive: true, force: true }));
const accessKeyId = 'AKIAIOSFODNN7EXAMPLE';
const secretAccessKey = 'wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY';
const emptyHash = 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855';

// Authoritative AWS vectors, not generated by this implementation:
// https://docs.amazonaws.cn/en_us/AmazonS3/latest/developerguide/sig-v4-header-based-auth.html
test('AWS official GET Object vector: canonical request, string to sign and signature match verbatim', () => {
  const result = signS3Request({ method: 'GET', url: 'https://examplebucket.s3.amazonaws.com/test.txt', headers: { range: 'bytes=0-9' }, accessKeyId, secretAccessKey, region: 'us-east-1', amzDate: '20130524T000000Z' });
  assert.equal(result.canonicalRequest, ['GET', '/test.txt', '', 'host:examplebucket.s3.amazonaws.com', 'range:bytes=0-9', `x-amz-content-sha256:${emptyHash}`, 'x-amz-date:20130524T000000Z', '', 'host;range;x-amz-content-sha256;x-amz-date', emptyHash].join('\n'));
  assert.equal(result.stringToSign, 'AWS4-HMAC-SHA256\n20130524T000000Z\n20130524/us-east-1/s3/aws4_request\n7344ae5b7ee6c3e7e6b0fe0640412a37625d1fbfff95c48bbb2dc43964946972');
  assert.equal(result.signature, 'f0e8bdb87c964420e857bd35b5d6ed310bd44f0170aba48dd91039c6036bdb41');
});

test('AWS official List Objects vector validates query sorting', () => {
  const result = signS3Request({ method: 'GET', url: 'https://examplebucket.s3.amazonaws.com/?prefix=J&max-keys=2', accessKeyId, secretAccessKey, region: 'us-east-1', amzDate: '20130524T000000Z' });
  assert.equal(result.stringToSign.split('\n').at(-1), 'df57d21db20da04d7fa30298dd4488ba3a2b47ca3a489c74750e0f1e7df1b9b7');
  assert.equal(result.signature, '34b48302e7b5fa45bde8084f4b7868a86f0a534bc59db6670ed5711ef69dc6f7');
});

test('virtual hosted URLs preserve base path, port and encoded object names', () => {
  assert.equal(buildS3Url({ endpoint: 'http://localhost:9000/api', bucket: 'backups', forcePathStyle: false }, 'qq/中文 a%!.qqab').href,
    'http://backups.localhost:9000/api/qq/%E4%B8%AD%E6%96%87%20a%25%21.qqab');
  assert.equal(buildS3Url({ bucket: 'backups', region: 'auto', endpoint: 'https://account.r2.cloudflarestorage.com', forcePathStyle: false }).host, 'backups.account.r2.cloudflarestorage.com');
  assert.throws(() => buildS3Url({ endpoint: `http://user:${secretAccessKey}@localhost`, bucket: 'backups' }), { message: 'S3 endpoint 无效' });
});

test('local S3: path-style CRUD, signed requests, XML entities, prefix and pagination', async t => {
  const objects = new Map();
  const requests = [];
  let transient = 0;
  const server = http.createServer(async (req, res) => {
    const url = new URL(req.url, 'http://localhost');
    requests.push({ method: req.method, url, headers: req.headers });
    assert.match(req.headers.authorization, /^AWS4-HMAC-SHA256 Credential=/);
    assert.ok(req.headers['x-amz-content-sha256']);
    if (url.pathname === '/backups/denied') { res.writeHead(403); res.end(secretAccessKey + accessKeyId); return; }
    if (url.pathname === '/backups/retry' && transient++ === 0) { res.writeHead(503); res.end('unavailable'); return; }
    if (url.searchParams.has('list-type')) {
      assert.equal(url.pathname, '/backups/');
      assert.equal(url.searchParams.get('list-type'), '2');
      assert.equal(url.searchParams.get('prefix'), 'qq/');
      const second = url.searchParams.get('continuation-token');
      if (second) assert.equal(second, 'next&+token');
      res.end(`<ListBucketResult xmlns="http://s3.amazonaws.com/doc/2006-03-01/"><IsTruncated>${!second}</IsTruncated>${second ? '' : '<NextContinuationToken>next&amp;+token</NextContinuationToken>'}<Contents><Key>${second ? 'qq/&#x4E2D;&#25991;.qqab' : 'qq/a&amp;b.qqab'}</Key><Size>3</Size><LastModified>2026-11-03T00:00:00Z</LastModified></Contents></ListBucketResult>`);
      return;
    }
    const key = decodeURIComponent(url.pathname.slice('/backups/'.length));
    if (req.method === 'PUT') { const chunks = []; for await (const chunk of req) chunks.push(chunk); objects.set(key, Buffer.concat(chunks)); res.end(); }
    else if (req.method === 'DELETE') { objects.delete(key); res.writeHead(204); res.end(); }
    else if (objects.has(key)) res.end(objects.get(key));
    else { res.writeHead(404); res.end(); }
  });
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const entry = { endpoint: `http://127.0.0.1:${server.address().port}`, bucket: 'backups', region: 'us-east-1', forcePathStyle: true, accessKeyId, secretAccessKey, prefix: 'qq/' };
  const target = createS3Target(entry);
  const key = 'qq/中文 a&%.qqab';
  await target.put(key, Buffer.from('abc'));
  assert.deepEqual(await target.get(key), Buffer.from('abc'));
  assert.deepEqual(await target.list(), [{ key: 'qq/a&b.qqab', size: 3, mtimeMs: Date.parse('2026-11-03T00:00:00Z') }, { key: 'qq/中文.qqab', size: 3, mtimeMs: Date.parse('2026-11-03T00:00:00Z') }]);
  assert.equal((await target.test()).ok, true);
  await target.put('retry', Buffer.from('retry'));
  assert.equal(transient, 2);
  await target.remove(key);
  await assert.rejects(target.get(key), { message: 'S3 请求失败（HTTP 404）' });
  await assert.rejects(target.get('denied'), error => !error.message.includes(secretAccessKey) && !error.message.includes(accessKeyId));
  assert.equal(requests.filter(r => r.url.pathname === '/backups/denied').length, 1);
  const invalid = createS3Target({ ...entry, secretAccessKey: '' });
  assert.deepEqual(await invalid.test(), { ok: false, message: 'S3 凭据缺失' });
});
